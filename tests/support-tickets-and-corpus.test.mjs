import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

const rootDir = process.cwd();

test("OmniRelay Knowledge Corpus & Support Ticket Escalation Verification", async (t) => {
  await t.test("Master Knowledge Corpus covers all platform domains with 3 pillars", async () => {
    const corpusModule = await import("../lib/omni-relay-knowledge-corpus.ts");
    const { OMNIRELAY_MASTER_KNOWLEDGE, searchMasterKnowledge } = corpusModule;

    assert.ok(Array.isArray(OMNIRELAY_MASTER_KNOWLEDGE), "Master knowledge corpus must be an array");
    assert.ok(OMNIRELAY_MASTER_KNOWLEDGE.length >= 15, "Corpus must have at least 15 detailed knowledge cards");

    // Verify all cards implement the 3 pillars
    for (const card of OMNIRELAY_MASTER_KNOWLEDGE) {
      assert.ok(card.id, "Card must have id");
      assert.ok(card.title, "Card must have title");
      assert.ok(card.category, "Card must have category");
      assert.ok(card.what && card.what.length > 20, `Card ${card.id} must define WHAT is it`);
      assert.ok(card.why && card.why.length > 20, `Card ${card.id} must define WHY it matters`);
      assert.ok(Array.isArray(card.how) && card.how.length > 0, `Card ${card.id} must define HOW it works`);
      assert.ok(Array.isArray(card.keywords) && card.keywords.length > 0, `Card ${card.id} must have keywords`);
    }

    // Verify retrieval works for core platform concepts
    const campaignResults = searchMasterKnowledge("broadcast csv excel media attachment");
    assert.ok(campaignResults.length > 0, "Must retrieve campaign knowledge cards");

    const templateResults = searchMasterKnowledge("11 templates 14 templates meta approved utility");
    assert.ok(templateResults.length > 0, "Must retrieve template knowledge cards");

    const notificationResults = searchMasterKnowledge("bell notifications appointment booking pwa push");
    assert.ok(notificationResults.length > 0, "Must retrieve notification knowledge cards");
  });

  await t.test("OmniRelay Guide seamlessly incorporates Master Knowledge Corpus", async () => {
    const guideModule = await import("../lib/omni-relay-guide.ts");
    const { OMNIRELAY_KNOWLEDGE } = guideModule;

    assert.ok(Array.isArray(OMNIRELAY_KNOWLEDGE), "Guide knowledge base must exist");
    assert.ok(OMNIRELAY_KNOWLEDGE.length >= 25, "Guide knowledge base must be enriched with master corpus");

    const guideFilePath = path.join(rootDir, "components/omni-relay-guide.tsx");
    const guideContent = fs.readFileSync(guideFilePath, "utf-8");

    // UI must provide support ticket escalation
    assert.ok(guideContent.includes("Raise Support Ticket") || guideContent.includes("Ask OmniRelay Team"), "Guide UI must include support escalation");
    assert.ok(guideContent.includes("ticketSubject"), "Guide UI must include ticket subject input");
    assert.ok(guideContent.includes("ticketPriority"), "Guide UI must include priority selection");
  });

  await t.test("Support Tickets Route enforces schema, RLS, and autogenerated ticket IDs", () => {
    const ticketRoutePath = path.join(rootDir, "app/api/support/ticket/route.ts");
    assert.ok(fs.existsSync(ticketRoutePath), "Support ticket route must exist");
    const content = fs.readFileSync(ticketRoutePath, "utf-8");

    assert.ok(content.includes("TKT-"), "Ticket route must autogenerate TKT- formatted ticket IDs");
    assert.ok(content.includes("support_tickets"), "Ticket route must write to support_tickets table");
    assert.ok(content.includes("support_ticket_created"), "Ticket route must audit ticket submissions");
  });

  await t.test("All outbound message routes strictly adhere to messages_content_schema", () => {
    const replyRoutePath = path.join(rootDir, "app/api/conversations/reply/route.ts");
    const startRoutePath = path.join(rootDir, "app/api/conversations/start/route.ts");

    const replyContent = fs.readFileSync(replyRoutePath, "utf-8");
    const startContent = fs.readFileSync(startRoutePath, "utf-8");

    // messages_content_schema requires type to be 'text', 'file', or 'data'
    assert.ok(
      replyContent.includes('type: mediaUrl ? "file" : "text"'),
      "Reply route must set type to 'file' or 'text'"
    );
    assert.ok(
      startContent.includes('type: "data"') && startContent.includes('kind: "template"'),
      "Start route must use type: 'data' and kind: 'template' to strictly comply with messages_content_schema"
    );
  });

  await t.test("Campaign upload route enforces resilient PDF fallback and RLS path structure", () => {
    const uploadRoutePath = path.join(rootDir, "app/api/campaigns/upload/route.ts");
    const content = fs.readFileSync(uploadRoutePath, "utf-8");

    assert.ok(content.includes("application/pdf"), "Must allow application/pdf");
    assert.ok(content.includes("clinic-brochures"), "Must include clinic-brochures fallback for PDF documents");
    assert.ok(content.includes("clinical-documents"), "Must include clinical-documents fallback");
    assert.ok(content.includes("${organization.id}/"), "Storage path must be prefixed with organization ID for RLS");
  });
});
